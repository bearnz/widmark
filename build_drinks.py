"""Rebuild drinks.json from data/abv_sources.csv and refresh the CSV's status column.

Each CSV row is one product: the ways it's served ('units', e.g. "can/bottle 330;
handle 425; pint 568", each a label and mL), the ABV each retailer lists (blank
where it lists none), the ABV the brewery itself lists, an old guess from memory,
and a manual column for values checked by hand. Spirits are logged by mL poured,
so their units are just quick picks. The status column records which ABV
drinks.json uses:

    manual      the manual value, which always wins
    brewery     the brewery's own value, over any retailer's (they copy it, sometimes wrongly)
    agree       retailers agree (within AGREE_WITHIN): that value
    conflict    retailers disagree: the higher one, until a manual value is set
    one source  only one retailer lists an ABV: that value
    generic     a row named "... (generic)": the typical value in the guess column
    guess only  only the old guess: listed with no ABV (the guess shown as a hint)
    missing     no ABV anywhere: listed with no ABV

Drinks with no ABV still go into drinks.json, with "abv": null, so the app can
list them and ask for one. The app's Set ABV button writes into the manual column
through set_manual() and rebuilds, the same as editing the CSV by hand.

Run it after editing the CSV:  uv run build_drinks.py
"""
import csv
import json
import sys
from pathlib import Path

import bac

SOURCES = Path(__file__).parent / "data" / "abv_sources.csv"
CATALOGUE = Path(__file__).parent / "drinks.json"
RETAILERS = {"liquorland": "Liquorland", "woolworths": "Woolworths", "new_world": "New World", "paknsave": "PAK'nSAVE"}
COLUMNS = ("drink", "type", "units", *RETAILERS, "brewery", "guess", "manual", "status", "note")
ABV_COLUMNS = (*RETAILERS, "brewery", "guess", "manual")
AGREE_WITHIN = 0.1
TYPE_ORDER = ("beer", "cider", "rtd", "wine", "spirit")
# ABVs outside these are possible but unusual for the type, so the report asks for a second look.
USUAL_ABV = {"beer": (2, 12), "cider": (2, 12), "rtd": (3, 12), "wine": (5, 22), "spirit": (15, 60)}
LEFT_OUT = ("guess only", "missing")
NEEDS_REVIEW = ("conflict",) + LEFT_OUT
NOTE = ("Generated by build_drinks.py from data/abv_sources.csv: edit the CSV, not this file. "
        "ABVs are as listed by Liquorland, Woolworths, New World, PAK'nSAVE and the breweries "
        "in October 2026.")


class BuildError(Exception):
    """The CSV has problems; nothing was written."""


def num(text):
    text = (text or "").strip()
    return float(text) if text else None


def resolve(row):
    """(status, abv) for one CSV row; abv is None when the drink is left out."""
    if num(row["manual"]) is not None:
        return "manual", num(row["manual"])
    if row["drink"].endswith("(generic)"):
        return "generic", num(row["guess"])
    if num(row["brewery"]) is not None:
        return "brewery", num(row["brewery"])
    found = [num(row[r]) for r in RETAILERS if num(row[r]) is not None]
    if len(found) > 1:
        return ("agree" if max(found) - min(found) <= AGREE_WITHIN else "conflict"), max(found)
    if found:
        return "one source", found[0]
    return ("guess only" if num(row["guess"]) is not None else "missing"), None


def parse_units(text):
    """'can/bottle 330; pint 568' -> [{'label': 'can/bottle', 'ml': 330.0}, ...]"""
    units = []
    for part in text.split(";"):
        label, _, ml = part.strip().rpartition(" ")
        if not label or not ml.replace(".", "", 1).isdigit():
            raise ValueError(f"can't read unit {part.strip()!r} in {text!r}; expected e.g. 'pint 568'")
        units.append({"label": label, "ml": float(ml)})
    return units


def problems(fields, rows):
    """Everything in the CSV that would make a wrong or broken drinks.json, by line."""
    missing = [c for c in COLUMNS if c not in (fields or [])]
    if missing:
        return [f"header: missing column(s) {', '.join(missing)}"]
    found, names = [], set()
    for line, row in enumerate(rows, start=2):
        name = (row["drink"] or "").strip()
        where = f"line {line} ({name or 'no name'})"
        if not name:
            found.append(f"{where}: the drink name is empty")
        elif name in names:
            found.append(f"{where}: another row has the same name")
        elif name[0] in "=+-@":
            found.append(f"{where}: starts with {name[0]!r}, which spreadsheets read as a formula")
        names.add(name)
        if row["type"] not in TYPE_ORDER:
            found.append(f"{where}: type {row['type']!r} isn't one of {', '.join(TYPE_ORDER)}")
        for col in ABV_COLUMNS:
            try:
                value = num(row[col])
            except ValueError:
                found.append(f"{where}: {col} {row[col]!r} isn't a number (use a dot for decimals)")
                continue
            if value is not None and not 0 < value <= bac.MAX_ABV:
                found.append(f"{where}: {col} {value:g} isn't a possible ABV")
        try:
            parse_units(row["units"] or "")
        except ValueError as e:
            found.append(f"{where}: {e}")
    return found


def unusual(rows):
    """Rows whose ABV in drinks.json is unusual for their type."""
    flagged = []
    for row in rows:
        abv = resolve(row)[1]
        low, high = USUAL_ABV[row["type"]]
        if abv is not None and not low <= abv <= high:
            flagged.append((row, abv))
    return flagged


def retailers_differ(rows):
    """Rows where a retailer lists a different ABV from the brewery (the brewery's is used)."""
    differ = []
    for row in rows:
        brewery = num(row["brewery"])
        if brewery is not None:
            off = {label: num(row[r]) for r, label in RETAILERS.items()
                   if num(row[r]) is not None and abs(num(row[r]) - brewery) > AGREE_WITHIN}
            if off:
                differ.append((row, brewery, off))
    return differ


def source(row, status):
    if status in ("manual", "generic"):
        return status
    if status == "brewery":
        return "brewery"
    return ", ".join(label for r, label in RETAILERS.items() if num(row[r]) is not None)


def read(sources):
    # utf-8-sig also reads the byte-order mark Excel adds when it saves "CSV UTF-8".
    with sources.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        return reader.fieldnames, list(reader)


def build(sources=SOURCES, out=CATALOGUE):
    """Rewrite the status column and drinks.json; return the rows with their status set.

    Raises BuildError, writing nothing, if any row has a problem.
    """
    fields, rows = read(sources)
    found = problems(fields, rows)
    if found:
        raise BuildError("\n".join(found))
    drinks = []
    for row in rows:
        row["status"], abv = resolve(row)
        drink = {"name": row["drink"], "type": row["type"], "abv": abv,
                 "units": parse_units(row["units"]), "pour": row["type"] == "spirit",
                 "source": source(row, row["status"]) if abv is not None else row["status"]}
        if abv is None and num(row["guess"]) is not None:
            drink["guess"] = num(row["guess"])
        drinks.append(drink)
    drinks.sort(key=lambda d: (TYPE_ORDER.index(d["type"]), d["name"].lower()))
    with sources.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    out.write_text(json.dumps({"_note": NOTE, "drinks": drinks}, indent=1) + "\n", encoding="utf-8")
    return rows


def set_manual(drink, abv, sources=SOURCES, out=CATALOGUE):
    """Put abv (or None to clear it) in a drink's manual column, then rebuild.

    The CSV is only rewritten if the whole table still builds; otherwise BuildError
    is raised and nothing changes.
    """
    if abv is not None:
        bac.check_abv(abv)
    fields, rows = read(sources)
    matches = [row for row in rows if row["drink"] == drink]
    if not matches:
        raise BuildError(f"{drink!r} isn't in {sources.name}")
    found = problems(fields, rows)
    if found:
        raise BuildError("\n".join(found))
    matches[0]["manual"] = "" if abv is None else f"{abv:g}"
    with sources.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    build(sources, out)


def main():
    try:
        rows = build()
    except BuildError as e:
        print(f"Nothing was written. Fix these in {SOURCES.name}, then run this again:\n{e}")
        return 1
    counts = {}
    for row in rows:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    without = sum(n for s, n in counts.items() if s in LEFT_OUT)
    print(f"drinks.json: {len(rows)} drinks, {without} of them with no ABV yet")
    print("  " + ", ".join(f"{s} {n}" for s, n in sorted(counts.items())))
    for status in NEEDS_REVIEW:
        flagged = [r for r in rows if r["status"] == status]
        if flagged:
            print(f"\n{status} ({len(flagged)}):")
            for r in flagged:
                seen = ", ".join(f"{label} {r[k]}" for k, label in RETAILERS.items() if r[k]) or "no retailer ABV"
                guess = f"; guess {r['guess']}" if r["guess"] else ""
                print(f"  {r['drink']}: {seen}{guess}")
    differ = retailers_differ(rows)
    if differ:
        print(f"\nretailers differ from the brewery, which is used ({len(differ)}):")
        for r, brewery, off in differ:
            print(f"  {r['drink']}: brewery {brewery:g}, " + ", ".join(f"{k} {v:g}" for k, v in off.items()))
    odd = unusual(rows)
    if odd:
        print(f"\nunusual ABV for the type, worth a second look ({len(odd)}):")
        for r, abv in odd:
            low, high = USUAL_ABV[r["type"]]
            print(f"  {r['drink']} ({r['type']}): {abv:g}%, usually {low}-{high}%")


if __name__ == "__main__":
    sys.exit(main())
