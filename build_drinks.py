"""Rebuild drinks.json from data/abv_sources.csv and refresh the CSV's status column.

Each CSV row is one product: the ways it's served ('units', e.g. "can/bottle 330;
handle 425; pint 568", each a label and mL), the ABV each retailer lists (blank
where it lists none), an old guess from memory, and a manual column for values
checked by hand. Spirits are logged by mL poured, so their units are just
quick picks. The status column records which ABV drinks.json uses:

    manual      the manual value, which always wins
    agree       retailers agree (within AGREE_WITHIN): that value
    conflict    retailers disagree: the higher one, until a manual value is set
    one source  only one retailer lists an ABV: that value
    generic     a row named "... (generic)": the typical value in the guess column
    guess only  only the old guess: left out of drinks.json
    missing     no ABV anywhere: left out of drinks.json

Run it after editing the CSV:  uv run build_drinks.py
"""
import csv
import json
import sys
from pathlib import Path

import app

SOURCES = Path(__file__).parent / "data" / "abv_sources.csv"
RETAILERS = {"liquorland": "Liquorland", "woolworths": "Woolworths", "new_world": "New World"}
AGREE_WITHIN = 0.1
TYPE_ORDER = ("beer", "cider", "rtd", "wine", "spirit")
LEFT_OUT = ("guess only", "missing")
NEEDS_REVIEW = ("conflict",) + LEFT_OUT
NOTE = ("Generated by build_drinks.py from data/abv_sources.csv: edit the CSV, not this file. "
        "ABVs are as listed by Liquorland, Woolworths and New World in October 2026.")


def num(text):
    text = (text or "").strip()
    return float(text) if text else None


def resolve(row):
    """(status, abv) for one CSV row; abv is None when the drink is left out."""
    if num(row["manual"]) is not None:
        return "manual", num(row["manual"])
    if row["drink"].endswith("(generic)"):
        return "generic", num(row["guess"])
    found = [num(row[r]) for r in RETAILERS if num(row[r]) is not None]
    if len(found) > 1:
        return ("agree" if max(found) - min(found) <= AGREE_WITHIN else "conflict"), max(found)
    if found:
        return "one source", found[0]
    return ("guess only" if num(row["guess"]) is not None else "missing"), None


def parse_units(text):
    """'can/bottle 330; pint 568' -> [{'label': 'can/bottle', 'ml': 330.0}, ...]"""
    units = []
    for part in text.split(";"):
        label, _, ml = part.strip().rpartition(" ")
        if not label or not ml.replace(".", "", 1).isdigit():
            raise ValueError(f"can't read unit {part.strip()!r} in {text!r}; expected e.g. 'pint 568'")
        units.append({"label": label, "ml": float(ml)})
    return units


def source(row, status):
    if status in ("manual", "generic"):
        return status
    return ", ".join(label for r, label in RETAILERS.items() if num(row[r]) is not None)


def build(sources=SOURCES, out=app.CATALOGUE):
    """Rewrite the status column and drinks.json; return the rows with their status set."""
    with sources.open(newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        fields, rows = reader.fieldnames, list(reader)
    drinks = []
    for row in rows:
        row["status"], abv = resolve(row)
        if abv is not None:
            drinks.append({"name": row["drink"], "type": row["type"], "abv": abv,
                           "units": parse_units(row["units"]), "pour": row["type"] == "spirit",
                           "source": source(row, row["status"])})
    drinks.sort(key=lambda d: (TYPE_ORDER.index(d["type"]), d["name"].lower()))
    with sources.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    out.write_text(json.dumps({"_note": NOTE, "drinks": drinks}, indent=1) + "\n", encoding="utf-8")
    return rows


def main():
    rows = build()
    counts = {}
    for row in rows:
        counts[row["status"]] = counts.get(row["status"], 0) + 1
    print(f"drinks.json: {sum(n for s, n in counts.items() if s not in LEFT_OUT)} drinks")
    print("  " + ", ".join(f"{s} {n}" for s, n in sorted(counts.items())))
    for status in NEEDS_REVIEW:
        flagged = [r for r in rows if r["status"] == status]
        if flagged:
            print(f"\n{status} ({len(flagged)}):")
            for r in flagged:
                seen = ", ".join(f"{label} {r[k]}" for k, label in RETAILERS.items() if r[k]) or "no retailer ABV"
                guess = f"; guess {r['guess']}" if r["guess"] else ""
                print(f"  {r['drink']}: {seen}{guess}")


if __name__ == "__main__":
    sys.exit(main())
